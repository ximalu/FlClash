uint64_t flclashtier_zt_snapshot_export(flclashtier_zt_snapshot* out) {
  if (!out) return 0;
  std::lock_guard<std::mutex> lock(g_snapMutex);
  memcpy(out, &g_snapshot, sizeof(g_snapshot));
  return g_generation;
}

void flclashtier_zt_set_socket_fd(int fd) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  g_sockFd = fd;
}

int flclashtier_zt_get_socket_fd(void) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  return g_sockFd;
}

int flclashtier_zt_process_wire_packet(const struct sockaddr_storage* remoteAddr,
                                       const void* data, unsigned int len,
                                       int64_t now, int64_t* nextDeadline) {
  volatile int64_t deadline = 0;
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return -1;
  enum ZT_ResultCode rc = ZT_Node_processWirePacket(s_node, NULL, now, -1,
      remoteAddr, data, len, &deadline);
  if (nextDeadline) *nextDeadline = static_cast<int64_t>(deadline);
  return static_cast<int>(rc);
}

int flclashtier_zt_process_background_tasks(int64_t now, int64_t* nextDeadline) {
  volatile int64_t deadline = 0;
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return -1;
  enum ZT_ResultCode rc = ZT_Node_processBackgroundTasks(s_node, NULL, now, &deadline);
  if (nextDeadline) *nextDeadline = static_cast<int64_t>(deadline);
  return static_cast<int>(rc);
}

int flclashtier_zt_join(uint64_t nwid) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return -1;
  return static_cast<int>(ZT_Node_join(s_node, nwid, NULL, NULL));
}

int flclashtier_zt_leave(uint64_t nwid) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return -1;
  void* nuptr = NULL;
  return static_cast<int>(ZT_Node_leave(s_node, nwid, &nuptr, NULL));
}

int flclashtier_zt_frame_pull(flclashtier_zt_frame* out) {
  if (!out) return 0;
  std::lock_guard<std::mutex> lock(g_frameMutex);
  if (g_frameCount <= 0) return 0;
  memcpy(out, &g_frameQueue[g_frameHead], sizeof(flclashtier_zt_frame));
  g_frameHead = (g_frameHead + 1) % FLCLASHTIER_ZT_FRAME_QUEUE;
  g_frameCount--;
  return 1;
}

int flclashtier_zt_frame_pending(void) {
  std::lock_guard<std::mutex> lock(g_frameMutex);
  return g_frameCount;
}

uint64_t flclashtier_zt_frame_dropped(void) {
  std::lock_guard<std::mutex> lock(g_frameMutex);
  return g_frameDropped;
}

int flclashtier_zt_send_frame(uint64_t nwid, uint64_t srcMac, uint64_t dstMac,
                              uint16_t etherType, uint16_t vlanId,
                              const void* data, unsigned int len,
                              int64_t* nextDeadline) {
  volatile int64_t deadline = 0;
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return -1;
  int64_t now = std::chrono::duration_cast<std::chrono::milliseconds>(
      std::chrono::system_clock::now().time_since_epoch()).count();
  enum ZT_ResultCode rc = ZT_Node_processVirtualNetworkFrame(s_node, NULL,
      now, nwid, srcMac, dstMac, etherType, vlanId, data, len, &deadline);
  if (nextDeadline) *nextDeadline = static_cast<int64_t>(deadline);
  return static_cast<int>(rc);
}

int flclashtier_zt_multicast_subscribe(uint64_t nwid, uint64_t multicastGroup, uint32_t adi) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return -1;
  return static_cast<int>(ZT_Node_multicastSubscribe(s_node, NULL, nwid, multicastGroup, adi));
}

int flclashtier_zt_multicast_unsubscribe(uint64_t nwid, uint64_t multicastGroup, uint32_t adi) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return -1;
  return static_cast<int>(ZT_Node_multicastUnsubscribe(s_node, nwid, multicastGroup, adi));
}

flclashtier_zt_node* flclashtier_zt_node_new(void) {
  ZT_Node_Callbacks cb;
  memset(&cb, 0, sizeof(cb));
  cb.version = 0;
  cb.statePutFunction = statePutFunction;
  cb.stateGetFunction = stateGetFunction;
  cb.wirePacketSendFunction = wirePacketSendFunction;
  cb.virtualNetworkFrameFunction = virtualNetworkFrameFunction;
  cb.virtualNetworkConfigFunction = virtualNetworkConfigFunction;
  cb.eventCallback = eventCallback;

  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (s_node) return reinterpret_cast<flclashtier_zt_node*>(s_node);  // already created
  ZT_Node* node = NULL;
  enum ZT_ResultCode rc = ZT_Node_new(&node, NULL, NULL, &cb, 0);
  if (rc != ZT_RESULT_OK || node == NULL) {
    return NULL;
  }
  s_node = node;
  return reinterpret_cast<flclashtier_zt_node*>(node);
}

void flclashtier_zt_node_delete(flclashtier_zt_node* node) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (node == NULL) return;
  if (s_node == reinterpret_cast<ZT_Node*>(node)) {
    s_node = NULL;
  }
  ZT_Node_delete(reinterpret_cast<ZT_Node*>(node));
}

uint64_t flclashtier_zt_node_address(void) {
  std::lock_guard<std::mutex> lock(g_nodeMutex);
  if (!s_node) return 0;
  return ZT_Node_address(s_node);
}

void flclashtier_zt_set_identity_path(const char* path) {
  if (path == NULL) { g_identityPath[0] = '\0'; return; }
  strncpy(g_identityPath, path, sizeof(g_identityPath) - 1);
  g_identityPath[sizeof(g_identityPath) - 1] = '\0';
}

const char* flclashtier_zt_version(void) {
  int major = 0, minor = 0, revision = 0;
  ZT_version(&major, &minor, &revision);
  static char buf[32];
  snprintf(buf, sizeof(buf), "%d.%d.%d", major, minor, revision);
  return buf;
}
